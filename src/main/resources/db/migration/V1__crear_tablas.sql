-- V1: Estructura inicial de VetCare

-- 1. ROLES
CREATE TABLE roles (
                       id_rol BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       nombre VARCHAR(150) NOT NULL UNIQUE
);

-- 2. USUARIO
CREATE TABLE usuario (
                         id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         nombres VARCHAR(100) NOT NULL,
                         apellidos VARCHAR(100) NOT NULL,
                         tipo_documento VARCHAR(20) NOT NULL,
                         nro_documento VARCHAR(20) NOT NULL UNIQUE,
                         correo VARCHAR(150) NOT NULL UNIQUE,
                         contrasena VARCHAR(255) NOT NULL,
                         nro_celular VARCHAR(20) NOT NULL,
                         id_rol BIGINT NOT NULL,
                         fecha_registro TIMESTAMP NOT NULL,

                         CONSTRAINT fk_usuario_rol
                             FOREIGN KEY (id_rol)
                                 REFERENCES roles(id_rol)
);

-- 3. PROPIETARIO
CREATE TABLE propietario (
                             id_propietario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             id_usuario BIGINT NOT NULL UNIQUE,
                             direccion VARCHAR(200) NOT NULL,
                             fecha_registro_clinica DATE NOT NULL,
                             estado_cliente VARCHAR(20) NOT NULL,

                             CONSTRAINT fk_propietario_usuario
                                 FOREIGN KEY (id_usuario)
                                     REFERENCES usuario(id_usuario)
);

-- 4. VETERINARIO
CREATE TABLE veterinario (
                             id_veterinario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             id_usuario BIGINT NOT NULL UNIQUE,
                             especialidad VARCHAR(255),
                             nro_colegiatura VARCHAR(255),

                             CONSTRAINT fk_veterinario_usuario
                                 FOREIGN KEY (id_usuario)
                                     REFERENCES usuario(id_usuario)
);

-- 5. MASCOTA
CREATE TABLE mascota (
                         id_mascota BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         id_propietario BIGINT NOT NULL,
                         nombre VARCHAR(100) NOT NULL,
                         especie VARCHAR(50) NOT NULL,
                         raza VARCHAR(100),
                         sexo VARCHAR(10),
                         fecha_nacimiento DATE,

                         CONSTRAINT fk_mascota_propietario
                             FOREIGN KEY (id_propietario)
                                 REFERENCES propietario(id_propietario)
);

-- 6. HISTORIA CLINICA
CREATE TABLE historia_clinica (
                                  id_historia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  id_mascota BIGINT NOT NULL UNIQUE,
                                  fecha_apertura TIMESTAMP NOT NULL,

                                  CONSTRAINT fk_historia_mascota
                                      FOREIGN KEY (id_mascota)
                                          REFERENCES mascota(id_mascota)
);

-- 7. CITA
CREATE TABLE cita (
                      id_cita BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      id_veterinario BIGINT NOT NULL,
                      id_mascota BIGINT NOT NULL,
                      fecha_cita TIMESTAMP NOT NULL,
                      estado VARCHAR(255) NOT NULL,
                      motivo_cita VARCHAR(255),

                      CONSTRAINT fk_cita_veterinario
                          FOREIGN KEY (id_veterinario)
                              REFERENCES veterinario(id_veterinario),

                      CONSTRAINT fk_cita_mascota
                          FOREIGN KEY (id_mascota)
                              REFERENCES mascota(id_mascota)
);

-- 8. ATENCIONES
CREATE TABLE atenciones (
                            id_atencion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            id_historia BIGINT NOT NULL,
                            id_veterinario_atencion BIGINT NOT NULL,
                            id_cita BIGINT NOT NULL UNIQUE,
                            fecha_atencion TIMESTAMP NOT NULL,
                            precio_atencion NUMERIC(38, 2),
                            peso NUMERIC(38, 2),
                            sintoma VARCHAR(255),
                            diagnostico VARCHAR(255),
                            tratamiento VARCHAR(255),
                            observacion VARCHAR(255),

                            CONSTRAINT fk_atencion_historia
                                FOREIGN KEY (id_historia)
                                    REFERENCES historia_clinica(id_historia),

                            CONSTRAINT fk_atencion_veterinario
                                FOREIGN KEY (id_veterinario_atencion)
                                    REFERENCES veterinario(id_veterinario),

                            CONSTRAINT fk_atencion_cita
                                FOREIGN KEY (id_cita)
                                    REFERENCES cita(id_cita)
);